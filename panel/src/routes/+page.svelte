												stroke-width="1.4"
												stroke-linecap="round"
											/>
											<path
												d="M13 3v3.2h-3.2"
												stroke="currentColor"
												stroke-width="1.4"
												stroke-linecap="round"
												stroke-linejoin="round"
											/>
										</svg>
										Rotate
									</button>
								</form>
								<form
									method="POST"
									action="?/delete"
									use:enhance
