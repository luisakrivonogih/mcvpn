<script lang="ts">
	import { enhance } from '$app/forms';
	import { env } from '$env/dynamic/public';
	import type { ActionData, PageData } from './$types';

	let { data, form }: { data: PageData; form: ActionData } = $props();

	let creating = $state(false);

	type RevealedSecret = {
		label: string;
		keyId: string;
		secret: string;
		mode: 'created' | 'rotated';
	};
	let revealedSecret = $state<RevealedSecret | null>(null);
	let copyFeedback = $state(false);

	// A local, live-updatable copy of the user list: form actions (create/
	// toggle/rotate/delete) refresh `data.users` via SvelteKit's own reload,
	// which this re-syncs from; the 5s poll below only patches `online`/
	// `lastSeenAt` in place on top of that, since those are the only fields
	// that change on their own between actions.
	let users = $state(data.users.map((u) => ({ ...u })));
	$effect(() => {
		users = data.users.map((u) => ({ ...u }));
	});

	$effect(() => {
		const interval = setInterval(async () => {
			let statuses: { id: string; online: boolean; lastSeenAt: string | null }[];
			try {
				const res = await fetch('/status');
				if (!res.ok) return;
				statuses = await res.json();
			} catch {
				return; // transient network error; try again on the next tick
			}
			const byId = new Map(statuses.map((s) => [s.id, s]));
			users = users.map((u) => {
				const s = byId.get(u.id);
				return s ? { ...u, online: s.online, lastSeenAt: s.lastSeenAt } : u;
			});
		}, 5000);
		return () => clearInterval(interval);
	});

	let enabledCount = $derived(users.filter((u) => u.enabled).length);

	$effect(() => {
		if (form && 'created' in form && form.created) {
			revealedSecret = {
				label: form.created.label,
				keyId: form.created.keyId,
				secret: form.created.secret,
				mode: 'created'
			};
		} else if (form && 'rotated' in form && form.rotated) {
			revealedSecret = {
				label: form.rotated.label,
				keyId: form.rotated.keyId,
				secret: form.rotated.secret,
				mode: 'rotated'
			};
		}
	});

	function dismissSecret() {
		revealedSecret = null;
		copyFeedback = false;
	}

	async function copySecret() {
		if (!revealedSecret) return;
		try {
			await navigator.clipboard.writeText(revealedSecret.secret);
			copyFeedback = true;
			setTimeout(() => (copyFeedback = false), 1500);
		} catch {
			// clipboard API can be unavailable (insecure context, permissions) - not fatal,
			// the admin can still select-and-copy the text manually.
		}
	}

	/** Builds this user's client config.toml and triggers a browser download. Only
	 * possible right after create/rotate, since that's the only time the plaintext
	 * secret is ever available at all. */
	function downloadConfig() {
		if (!revealedSecret) return;
		const host = env.PUBLIC_MC_HOST || '127.0.0.1';
		const port = env.PUBLIC_MC_PORT || '25565';
		const toml = `# Generated by the mcvpn admin panel for "${revealedSecret.label}".
# Fill in / adjust proxy_listen below if this client shouldn't use the default.
server_host = "${host}"
server_port = ${port}
username_prefix = "mcvpn_"
proxy_listen = "127.0.0.1:8080"
key_id = "${revealedSecret.keyId}"
key_secret = "${revealedSecret.secret}"
`;
		const blob = new Blob([toml], { type: 'application/toml' });
		const url = URL.createObjectURL(blob);
		const a = document.createElement('a');
		const safeLabel = revealedSecret.label.replace(/[^a-z0-9_-]+/gi, '_');
		a.href = url;
		a.download = `mcvpn-${safeLabel}.toml`;
		a.click();
		URL.revokeObjectURL(url);
	}

	function truncateHex(value: string, head = 8, tail = 6) {
		if (value.length <= head + tail + 1) return value;
		return `${value.slice(0, head)}…${value.slice(-tail)}`;
	}

	function formatDate(value: string | null) {
		if (!value) return '—';
		const d = new Date(value);
		return Number.isNaN(d.getTime()) ? value : d.toLocaleString();
	}

	function confirmDelete(label: string) {
		return confirm(`Delete VPN user "${label}"? This cannot be undone.`);
	}

	function confirmRotate(label: string) {
		return confirm(
			`Rotate the secret for "${label}"? The current secret will stop working immediately.`
		);
	}
</script>

