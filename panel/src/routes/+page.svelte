						stroke="currentColor"
						stroke-width="1.4"
						stroke-linecap="round"
						stroke-linejoin="round"
					/>
				</svg>
				Download config.toml
			</button>
			<button type="button" class="ghost dismiss-btn" onclick={dismissSecret}>Dismiss</button>
		</div>
	</div>
{/if}

<section class="create-user card">
