												<path d="M5.8 8.3 7.2 9.7 10.3 6.5" stroke="currentColor" stroke-width="1.4" stroke-linecap="round" stroke-linejoin="round" />
											</svg>
										{/if}
										{user.enabled ? 'Disable' : 'Enable'}
									</button>
								</form>
								<form
